//! Minimal KTX 2.0 writer: 2D, one layer, one face, no supercompression.
//! Specification: Khronos "KTX File Format Specification 2.0".

use ballistic_bundle::TextureFormat;

const IDENTIFIER: [u8; 12] = [
    0xAB, 0x4B, 0x54, 0x58, 0x20, 0x32, 0x30, 0xBB, 0x0D, 0x0A, 0x1A, 0x0A,
];

fn block_bytes(format: TextureFormat) -> usize {
    match format {
        TextureFormat::Bc1Srgb => 8,
        TextureFormat::Bc3Srgb => 16,
        TextureFormat::Rgba8Srgb => 4,
    }
}

fn ktx_format(format: TextureFormat) -> ::ktx2::Format {
    match format {
        TextureFormat::Bc1Srgb => ::ktx2::Format::BC1_RGB_SRGB_BLOCK,
        TextureFormat::Bc3Srgb => ::ktx2::Format::BC3_SRGB_BLOCK,
        TextureFormat::Rgba8Srgb => ::ktx2::Format::R8G8B8A8_SRGB,
    }
}

/// Data Format Descriptor (`dfdTotalSize` + one basic block), generated by
/// the `ktx2` crate's reference tables.
fn dfd(format: TextureFormat) -> (Vec<u8>, u32) {
    let (basic, type_size) = ::ktx2::dfd::Basic::from_format(ktx_format(format))
        .expect("all bundle texture formats have a DFD");
    let block = ::ktx2::dfd::Block::Basic(basic).to_vec();
    let mut out = ((4 + block.len()) as u32).to_le_bytes().to_vec();
    out.extend_from_slice(&block);
    (out, type_size)
}

/// Serialises a texture. `levels[0]` is the full-size image.
pub fn write(format: TextureFormat, width: u32, height: u32, levels: &[Vec<u8>]) -> Vec<u8> {
    let level_count = levels.len();
    let (dfd, type_size) = dfd(format);
    let header_end = 12 + 9 * 4 + 4 * 4 + 2 * 8 + level_count * 24;
    let dfd_offset = header_end;
    let mut data_start = dfd_offset + dfd.len();

    // Level data goes smallest first, each aligned to lcm(block size, 4).
    let align = block_bytes(format).max(4);
    let mut offsets = vec![0usize; level_count];
    for i in (0..level_count).rev() {
        data_start = data_start.next_multiple_of(align);
        offsets[i] = data_start;
        data_start += levels[i].len();
    }

    let mut out = Vec::with_capacity(data_start);
    out.extend_from_slice(&IDENTIFIER);
    for v in [
        format.vk_format(),
        type_size,
        width,
        height,
        0, // pixelDepth
        0, // layerCount
        1, // faceCount
        level_count as u32,
        0, // supercompressionScheme
    ] {
        out.extend_from_slice(&v.to_le_bytes());
    }
    for v in [dfd_offset as u32, dfd.len() as u32, 0, 0] {
        out.extend_from_slice(&v.to_le_bytes());
    }
    out.extend_from_slice(&0u64.to_le_bytes()); // sgd offset
    out.extend_from_slice(&0u64.to_le_bytes()); // sgd length
    for (i, l) in levels.iter().enumerate() {
        for v in [offsets[i] as u64, l.len() as u64, l.len() as u64] {
            out.extend_from_slice(&v.to_le_bytes());
        }
    }
    out.extend_from_slice(&dfd);
    for i in (0..level_count).rev() {
        out.resize(offsets[i], 0);
        out.extend_from_slice(&levels[i]);
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_with_reference_reader() {
        for (format, block) in [
            (TextureFormat::Bc1Srgb, 8usize),
            (TextureFormat::Bc3Srgb, 16),
            (TextureFormat::Rgba8Srgb, 4),
        ] {
            // 8x8 → 4x4 → 2x2 → 1x1
            let levels: Vec<Vec<u8>> = [8usize, 4, 2, 1]
                .iter()
                .map(|&s| {
                    let n = if block == 4 {
                        s * s
                    } else {
                        s.div_ceil(4).pow(2)
                    };
                    vec![0x5A; n * block]
                })
                .collect();
            let bytes = write(format, 8, 8, &levels);
            let r = ktx2::Reader::new(&bytes[..]).expect("valid ktx2");
            let h = r.header();
            assert_eq!(h.format.map(|f| f.value()), Some(format.vk_format()));
            assert_eq!(h.type_size, 1);
            assert_eq!((h.pixel_width, h.pixel_height, h.level_count), (8, 8, 4));
            let parsed: Vec<&[u8]> = r.levels().map(|l| l.data).collect();
            for (a, b) in parsed.iter().zip(&levels) {
                assert_eq!(*a, b.as_slice());
            }
            assert_eq!(r.dfd_blocks().len(), 1);
        }
    }
}
